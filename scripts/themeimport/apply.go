package main

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"
)

// themesStart/themesEnd and sessionsStart/sessionsEnd bound the two regions of brand/tokens.css
// this importer owns. BLG-474 review (round 2): the splice used to match a hand-written comment
// whose wording named the exact scheme count, so every scheme added or dropped meant editing the
// marker text too — any drift between what the comment claimed and what was really spliced would
// go unnoticed. A fixed sentinel, independent of content, both sides (generator and drift test)
// agree on forever.
const (
	themesStart   = "/* BLG-474:THEMES:START — generated by scripts/themeimport; do not hand-edit. */"
	themesEnd     = "/* BLG-474:THEMES:END */"
	sessionsStart = "/* BLG-474:SESSIONS:START — generated by scripts/themeimport; do not hand-edit. */"
	sessionsEnd   = "/* BLG-474:SESSIONS:END */"
)

// generateTokensCSS returns current with the two BLG-474-owned sections replaced by fresh output
// from every entry in BundledThemes — the only way those sections are meant to change. Content
// outside the markers (including the markers themselves) is preserved byte-for-byte.
func generateTokensCSS(current string) (string, error) {
	themesBody, err := renderThemesSection()
	if err != nil {
		return "", err
	}
	out, err := spliceSection(current, themesStart, themesEnd, themesBody)
	if err != nil {
		return "", fmt.Errorf("themes section: %w", err)
	}
	sessionsBody, err := renderSessionsSection()
	if err != nil {
		return "", err
	}
	out, err = spliceSection(out, sessionsStart, sessionsEnd, sessionsBody)
	if err != nil {
		return "", fmt.Errorf("sessions section: %w", err)
	}
	return out, nil
}

// spliceSection replaces everything strictly between startMarker and endMarker (exclusive of the
// markers themselves) with body, which is sandwiched between a leading and trailing newline so the
// markers always sit on their own lines regardless of what body ends with.
func spliceSection(content, startMarker, endMarker, body string) (string, error) {
	start := strings.Index(content, startMarker)
	if start < 0 {
		return "", fmt.Errorf("marker not found: %s", startMarker)
	}
	afterStart := start + len(startMarker)
	end := strings.Index(content[afterStart:], endMarker)
	if end < 0 {
		return "", fmt.Errorf("marker not found: %s", endMarker)
	}
	end += afterStart
	return content[:afterStart] + "\n" + strings.TrimRight(body, "\n") + "\n" + content[end:], nil
}

// renderThemesSection renders every bundled theme's main block, each preceded by a comment naming
// its license and source.
func renderThemesSection() (string, error) {
	var blocks []string
	for _, b := range BundledThemes {
		sch, err := loadBundled(b)
		if err != nil {
			return "", err
		}
		blocks = append(blocks, fmt.Sprintf("/* %s — %s, bundled under %s. Palette: %s. Port: %s. Source: %s */\n",
			b.Name, b.ID, b.License, b.PaletteOwner, b.PortBy, b.Source)+renderBlock(b.ID, mapTokens(sch)))
	}
	return strings.Join(blocks, "\n"), nil
}

// renderSessionsSection renders every bundled theme's session-color override block.
func renderSessionsSection() (string, error) {
	var blocks []string
	for _, b := range BundledThemes {
		sch, err := loadBundled(b)
		if err != nil {
			return "", err
		}
		blocks = append(blocks, renderSessionBlock(b.ID, sessionColors(sch)))
	}
	return strings.Join(blocks, "\n"), nil
}

// applyToRepo reads root/brand/tokens.css, regenerates its BLG-474 sections, and writes the result
// back to it and its two byte-identical copies — the only supported way to change what a bundled
// theme looks like in the shipped file.
func applyToRepo(root string) error {
	path := filepath.Join(root, "brand", "tokens.css")
	raw, err := os.ReadFile(path)
	if err != nil {
		return err
	}
	out, err := generateTokensCSS(string(raw))
	if err != nil {
		return err
	}
	for _, rel := range []string{
		filepath.Join("brand", "tokens.css"),
		filepath.Join("packages", "chat", "src", "theme", "brand.css"),
		filepath.Join("core", "internal", "landing", "static", "tokens.css"),
	} {
		if err := os.WriteFile(filepath.Join(root, rel), []byte(out), 0o644); err != nil {
			return err
		}
	}
	return nil
}
