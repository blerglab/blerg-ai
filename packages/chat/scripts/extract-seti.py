"""Extract the curated Seti WOFF outlines as inline SVG paths (requires fontTools).

Usage: python3 scripts/extract-seti.py /path/to/vscode/extensions/theme-seti
The source must include ThirdPartyNotices.txt; review it before running.
"""
import hashlib
import json
import sys
from pathlib import Path

from fontTools.pens.boundsPen import BoundsPen
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont

source = Path(sys.argv[1])
notice = (source / 'ThirdPartyNotices.txt').read_text()
assert 'Copyright (c) 2014 Jesse Weed' in notice
assert 'Permission is hereby granted, free of charge' in notice
mapping = json.loads((source / 'icons/vs-seti-icon-theme.json').read_text())
font = TTFont(source / 'icons/seti.woff')
glyphs = font.getGlyphSet()
cmap = font.getBestCmap()
# Public IDs are independent of the font's private-use code points.
chosen = {
    'file': 'default', 'go': 'go2', 'markdown': 'markdown', 'json': 'json', 'yaml': 'yml',
    'typescript': 'typescript', 'javascript': 'javascript', 'react': 'react', 'python': 'python',
    'shell': 'shell', 'powershell': 'powershell', 'docker': 'docker', 'makefile': 'makefile',
    'lock': 'lock', 'image': 'image', 'svg': 'svg', 'html': 'html', 'css': 'css', 'sass': 'sass',
    'less': 'less', 'rust': 'rust', 'c': 'c', 'cpp': 'cpp', 'csharp': 'c-sharp', 'java': 'java',
    'kotlin': 'kotlin', 'swift': 'swift', 'ruby': 'ruby', 'php': 'php', 'vue': 'vue', 'svelte': 'svelte',
    'config': 'config', 'npm': 'npm', 'database': 'db', 'csv': 'csv', 'pdf': 'pdf', 'archive': 'zip',
    'audio': 'audio', 'video': 'video', 'font': 'font', 'git': 'git', 'github': 'github',
    'license': 'license', 'terraform': 'terraform', 'lua': 'lua', 'xml': 'xml', 'notebook': 'notebook',
}
# Include the full upstream permission notice in emitted JavaScript too.
license_text = notice[notice.index('Copyright (c) 2014 Jesse Weed'):].strip()
lines = ['/*! Seti UI — https://github.com/jesseweed/seti-ui', license_text, '*/',
         '// Generated by scripts/extract-seti.py; normalized to a 16×16 SVG canvas.',
         '// Source: microsoft/vscode df53daabb18cd157bdb08c7f01c34df936cf12f4, extensions/theme-seti.',
         'export const fileIconPaths = {']
for name, original in chosen.items():
    code = int(mapping['iconDefinitions']['_' + original]['fontCharacter'][1:], 16)
    glyph = glyphs[cmap[code]]
    bounds = BoundsPen(glyphs)
    glyph.draw(bounds)
    x0, y0, x1, y1 = bounds.bounds
    scale = 14 / max(x1 - x0, y1 - y0)
    pen = SVGPathPen(glyphs, ntos=lambda value: format(value, '.3f').rstrip('0').rstrip('.') or '0')
    glyph.draw(TransformPen(pen, (scale, 0, 0, -scale, 8 - scale * (x0 + x1) / 2, 8 + scale * (y0 + y1) / 2)))
    lines.append(f"  {name}: {json.dumps(pen.getCommands())},")
# Blerg's folder silhouettes/badges are original; Seti does not provide named folders.
folders = {
    'folder': '', 'folder-src': 'M6 8 4 10l2 2m4-4 2 2-2 2',
    'folder-docs': 'M6 7.5h4v5H6zM7 9h2m-2 1.5h2',
    'folder-github': None, 'folder-test': 'm5.5 10 1.5 1.5 3.5-3.5',
    'folder-node': None, 'folder-public': 'M4.5 12 7 8.5l2 2 1-1 2 2.5z',
}
for name, path in folders.items():
    # The two logo badges are scaled versions of already bundled glyphs.
    if path is None:
        original = 'github' if name == 'folder-github' else 'npm'
        code = int(mapping['iconDefinitions']['_' + original]['fontCharacter'][1:], 16)
        glyph = glyphs[cmap[code]]
        bounds = BoundsPen(glyphs)
        glyph.draw(bounds)
        x0, y0, x1, y1 = bounds.bounds
        scale = 7 / max(x1 - x0, y1 - y0)
        pen = SVGPathPen(glyphs, ntos=lambda value: format(value, '.3f').rstrip('0').rstrip('.') or '0')
        glyph.draw(TransformPen(pen, (scale, 0, 0, -scale, 8 - scale * (x0 + x1) / 2, 10 + scale * (y0 + y1) / 2)))
        path = pen.getCommands()
    lines.append(f"  '{name}': {json.dumps(path or 'M2 13V3h4l2 2h6v8z')},")
lines += ['} as const', '', 'export type FileIconKind = keyof typeof fileIconPaths', '']
(Path(__file__).resolve().parent.parent / 'src/components/fileIconPaths.ts').write_text('\n'.join(lines))
for filename in ['ThirdPartyNotices.txt', 'README.md', 'package.json', 'icons/seti.woff', 'icons/vs-seti-icon-theme.json']:
    print(hashlib.sha256((source / filename).read_bytes()).hexdigest(), filename)
print(f'{len(chosen)} Seti glyphs, {len(folders)} folder variants')
