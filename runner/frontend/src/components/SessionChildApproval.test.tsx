import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest'
import { act, fireEvent, render, screen, waitFor } from '@testing-library/react'
import SessionChildApproval from './SessionChildApproval'
const request = vi.fn()
vi.mock('../apiFetch', () => ({ apiFetch: (...args: unknown[]) => request(...args) }))
const runtime = (name = 'docker') => ({runtime: name, enabled: false, partial: false, allowed_engines: ['claude', 'codex', 'hermes'], granted_engines: [] as string[], standing_rule_engines: [] as string[], effective_allowed_engines: [] as string[], can_enable: true, reason: ''})
const view = () => ({revision: 'rev-a', daemon_id: 'desktop-a', allowed_engines: ['claude','codex','hermes'], runtimes: [runtime(),runtime('daemon')]})
const ok = (body: unknown) => ({ok: true, json: async () => body})
const label = 'Start sandboxed children without asking'
describe('session child approvals', () => {
 beforeEach(() => request.mockReset())
 afterEach(() => vi.useRealTimers())
 it('discovers engines without preapproving on load', async () => {
  request.mockResolvedValue(ok(view()));render(<SessionChildApproval sessionId="parent-a" />)
  expect(await screen.findByRole('checkbox',{name:label})).not.toBeChecked()
  expect(screen.getAllByText(/Claude, Codex, Hermes/).length).toBeGreaterThan(0)
  expect(screen.getByRole('checkbox',{name:/unsandboxed/})).not.toBeChecked()
  expect(request).toHaveBeenCalledTimes(1)
 })
 it('offers a cluster parent one cluster control and writes runtime cluster',async()=>{
  request.mockResolvedValueOnce(ok({...view(),daemon_id:'cluster',runtimes:[runtime('cluster')]})).mockResolvedValueOnce(ok({...view(),daemon_id:'cluster',revision:'rev-b',runtimes:[{...runtime('cluster'),enabled:true,granted_engines:['claude']}]}))
  render(<SessionChildApproval sessionId="parent-a" />)
  const box=await screen.findByRole('checkbox',{name:'Start children on the cluster without asking'})
  expect(screen.queryByText(/full filesystem access/)).not.toBeInTheDocument()
  expect(screen.getByText(/Children of this session on the cluster/)).toBeInTheDocument()
  fireEvent.click(box)
  await waitFor(()=>expect(request).toHaveBeenCalledTimes(2))
  expect(JSON.parse(request.mock.calls[1][1].body)).toEqual({runtime:'cluster',enabled:true,revision:'rev-a'})
 })
 it('writes only the selected runtime against the displayed revision',async()=>{
  request.mockResolvedValueOnce(ok(view())).mockResolvedValueOnce(ok({...view(),revision:'rev-b',runtimes:[{...runtime(),enabled:true,granted_engines:['claude','codex','hermes']},runtime('daemon')]}))
  render(<SessionChildApproval sessionId="parent-a" />)
  fireEvent.click(await screen.findByRole('checkbox',{name:label}))
  await waitFor(()=>expect(request).toHaveBeenCalledTimes(2))
  expect(request.mock.calls[1][0]).toBe('/api/sessions/parent-a/child-approval')
  expect(JSON.parse(request.mock.calls[1][1].body)).toEqual({runtime:'docker',enabled:true,revision:'rev-a'})
  await waitFor(()=>expect(screen.getByRole('checkbox',{name:label})).toBeChecked())
  expect(screen.getByRole('checkbox',{name:/unsandboxed/})).not.toBeChecked()
 })
 it('shows a partial existing grant and allows revoking it while offline',async()=>{
  request.mockResolvedValue(ok({...view(),runtimes:[{...runtime(),partial:true,granted_engines:['hermes'],can_enable:false,reason:'Desktop disconnected.'}]}))
  render(<SessionChildApproval sessionId="parent-a" />)
  const input=await screen.findByRole('checkbox',{name:label})
  await waitFor(()=>expect(input).toBePartiallyChecked())
  fireEvent.click(screen.getByRole('button',{name:'Revoke sandboxed children'}))
  await waitFor(()=>expect(request).toHaveBeenCalledTimes(2))
  expect(JSON.parse(request.mock.calls[1][1].body).enabled).toBe(false)
 })
 it('refreshes changed scope after a conflict without retrying the grant',async()=>{
  request.mockResolvedValueOnce(ok(view())).mockResolvedValueOnce({ok:false,status:409}).mockResolvedValueOnce(ok({...view(),revision:'rev-new'}))
  render(<SessionChildApproval sessionId="parent-a" />)
  fireEvent.click(await screen.findByRole('checkbox',{name:label}))
  expect(await screen.findByRole('alert')).toHaveTextContent(/changed.*review/i)
  expect(request).toHaveBeenCalledTimes(3)
  expect(screen.getByRole('checkbox',{name:label})).not.toBeChecked()
  expect(screen.getByRole('checkbox',{name:label})).not.toBeDisabled()
  expect(screen.queryByText('Saving child approval…')).not.toBeInTheDocument()
  request.mockResolvedValueOnce(ok(view()))
  fireEvent.click(screen.getByRole('checkbox',{name:label}))
  await waitFor(()=>expect(request).toHaveBeenCalledTimes(4))
  expect(JSON.parse(request.mock.calls[3][1].body).revision).toBe('rev-new')
 })
 it('explains that desktop standing rules remain effective',async()=>{
  request.mockResolvedValue(ok({...view(),runtimes:[{...runtime(),standing_rule_engines:['codex'],effective_allowed_engines:['codex']}]}))
  render(<SessionChildApproval sessionId="parent-a" />)
  expect(await screen.findByText(/Desktop rules still allow Codex/)).toBeInTheDocument()
  expect(screen.getByText(/does not change desktop rules/i)).toBeInTheDocument()
 })
 it.each([null,{...view(),revision:[]},{...view(),runtimes:[{...runtime(),enabled:'true'}]},{...view(),runtimes:[{...runtime(),runtime:['docker']}]}])('fails closed on malformed authority',async body=>{
  request.mockResolvedValue(ok(body));render(<SessionChildApproval sessionId="parent-a" />)
  expect(await screen.findByRole('alert')).toBeInTheDocument()
  expect(screen.queryByRole('checkbox')).not.toBeInTheDocument()
 })
 it('bounds a stalled read and ignores its late authority',async()=>{
  vi.useFakeTimers()
  let resolve!: (value: unknown)=>void
  request.mockReturnValueOnce(new Promise(done=>{resolve=done}))
  render(<SessionChildApproval sessionId="parent-a" />)
  await act(async()=>{await Promise.resolve();await vi.advanceTimersByTimeAsync(10_001)})
  expect(screen.getByRole('alert')).toHaveTextContent('Could not load')
  await act(async()=>resolve(ok(view())))
  expect(screen.queryByRole('checkbox')).not.toBeInTheDocument()
 })
 it('does not treat an unconfirmed write as granted',async()=>{
  request.mockResolvedValueOnce(ok(view())).mockReturnValueOnce(new Promise(()=>{}))
  render(<SessionChildApproval sessionId="parent-a" />)
  const input=await screen.findByRole('checkbox',{name:label})
  fireEvent.click(input)
  expect(input).not.toBeChecked();expect(input).toBeDisabled()
 })
 it('keeps a later write busy when an expired write finally resolves',async()=>{
  request.mockResolvedValueOnce(ok(view()))
  render(<SessionChildApproval sessionId="parent-a" />)
  await screen.findByRole('checkbox',{name:label})
  let oldDone!: (value:unknown)=>void
  request.mockReturnValueOnce(new Promise(done=>{oldDone=done}))
  vi.useFakeTimers()
  fireEvent.click(screen.getByRole('checkbox',{name:label}))
  await act(async()=>{await vi.advanceTimersByTimeAsync(10_001)})
  expect(screen.getByRole('alert')).toHaveTextContent('Could not confirm')
  request.mockResolvedValueOnce(ok({...view(),revision:'fresh'}))
  await act(async()=>{fireEvent.click(screen.getByRole('button',{name:'Refresh'}))})
  let newDone!: (value:unknown)=>void
  request.mockReturnValueOnce(new Promise(done=>{newDone=done}))
  fireEvent.click(screen.getByRole('checkbox',{name:label}))
  await act(async()=>oldDone(ok(view())))
  expect(screen.getByRole('checkbox',{name:label})).toBeDisabled()
  expect(screen.getByRole('status')).toHaveTextContent('Saving')
  await act(async()=>newDone(ok(view())))
  expect(screen.getByRole('checkbox',{name:label})).not.toBeDisabled()
 })
 it('releases saving when a conflict refresh itself stalls',async()=>{
  request.mockResolvedValueOnce(ok(view()))
  render(<SessionChildApproval sessionId="parent-a" />)
  await screen.findByRole('checkbox',{name:label})
  request.mockResolvedValueOnce({ok:false,status:409}).mockReturnValueOnce(new Promise(()=>{}))
  vi.useFakeTimers()
  await act(async()=>fireEvent.click(screen.getByRole('checkbox',{name:label})))
  await act(async()=>{await vi.advanceTimersByTimeAsync(10_001)})
  expect(screen.queryByText('Saving child approval…')).not.toBeInTheDocument()
  expect(screen.getByRole('button',{name:'Refresh'})).not.toBeDisabled()
 })
 it('supports a newly registered engine without hardcoded choices',async()=>{
  request.mockResolvedValue(ok({...view(),runtimes:[{...runtime(),allowed_engines:['future-engine']}]}))
  render(<SessionChildApproval sessionId="parent-a" />)
  expect(await screen.findByText('Engines: future-engine')).toBeInTheDocument()
 })
 it('hides unsupported controls on an old server',async()=>{
  request.mockResolvedValue({ok:false,status:404});render(<SessionChildApproval sessionId="parent-a" />)
  await waitFor(()=>expect(screen.queryByText('Loading child approvals…')).not.toBeInTheDocument())
  expect(screen.queryByRole('checkbox')).not.toBeInTheDocument()
 })
 it('ignores stale responses after switching sessions',async()=>{
  let resolve!: (value: unknown)=>void
  request.mockReturnValueOnce(new Promise(done=>{resolve=done})).mockResolvedValueOnce({ok:false,status:404})
  const mounted=render(<SessionChildApproval sessionId="parent-a" />)
  await waitFor(()=>expect(request).toHaveBeenCalledTimes(1))
  mounted.rerender(<SessionChildApproval sessionId="parent-b" />)
  resolve(ok(view()))
  await waitFor(()=>expect(screen.queryByText('Loading child approvals…')).not.toBeInTheDocument())
  expect(screen.queryByRole('checkbox')).not.toBeInTheDocument()
 })
})
